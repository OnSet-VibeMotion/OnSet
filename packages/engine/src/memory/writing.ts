/** 故障整理与人评互学共用的经验写法；不改变已有记忆文件的格式。 */
export function lessonWritingGuide(): string {
  return `## 怎样总结才会改善下一次视频

一条经验只解决一个能说清的制作决策。description 写成「什么情况下，采用什么做法」的召回钩子；
正文在 600 字内交代下面五件事，可合成短段，不必机械地分五个标题：

- 适用条件：遇到什么画面、信息或时间约束才用；features / keywords 选可从新镜头识别的信号。
- 具体做法：写出可执行的步骤、时序或参数关系，同时给出反例与正例。保留决定结果的数值，
  但一次镜头里的偶然数值要换成随画幅、帧率、文字长度或口播时间变化的关系。
- 原因：说明这个做法怎样避免问题或改善观看体验；把观察到的差别与推测的原因分开。
- 边界：什么时候不适用、与哪些要求冲突时应让位；证据只覆盖一种情况时不要写「一律」。
- 验证方式：说明下一次怎样检查有没有做到，并与 checked_by 对应；机器查不出的观感交给人评。

证据只支持它实际观察到的事：没有失败源码就不能断言具体错误写法；相近镜头的通过只是参考，
不能证明改动造成了改善；未运行的事后检查不能写成已经通过。没有对照时只提出待验证的做法。
从人的胜负评判中提炼可迁移的构图、节奏、层次和信息展开方式，不把老师源码中的每处差别都当成胜因。
技术检查通过只说明相应检查过关，不等于画面更好。用户长期取向归偏好，一次修改归本次任务。
不要把「更高级」「更有节奏」「注意可读性」当成做法，也不要照抄项目文案或整段作品。

`;
}
