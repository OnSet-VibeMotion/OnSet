export const BuiltinAssetsRelDir = 'assets/builtin';
export const BuiltinManifestFile = 'manifest.json';
export const BuiltinLicense = 'MIT';
export const BuiltinLicenseNotice =
  'Procedurally generated by OnSet engine under MIT License. Zero third-party copyright encumbrance.';

export type BuiltinAssetKind = 'texture' | 'sfx';
export type BuiltinAssetStatus = 'created' | 'unchanged' | 'preserved' | 'overwritten';

export interface BuiltinAssetEntry {
  id: string;
  file: string;
  kind: BuiltinAssetKind;
  format: 'svg' | 'wav';
  license: string;
  description: string;
  bytes: number;
  sha256: string;
  user_modified: boolean;
  width?: number;
  height?: number;
  duration_seconds?: number;
  sample_rate?: number;
  channels?: number;
  bit_depth?: number;
  rms_db?: number;
  sample_peak_db?: number;
  true_peak_dbtp?: number;
}

export interface BuiltinAssetsManifest {
  version: 1;
  license: string;
  license_notice: string;
  assets: BuiltinAssetEntry[];
}

export interface GeneratedBuiltinAssetResult extends BuiltinAssetEntry {
  status: BuiltinAssetStatus;
}

export interface GenerateBaseAssetsOptions {
  /** 强制覆盖项目里已被用户修改的同名文件（默认 false，保护用户改动）。 */
  force?: boolean;
  /** 可选：仅生成指定的内置素材 ID（如 ['paper', 'whoosh']）。 */
  only?: readonly string[];
}

export interface GenerateBaseAssetsResult {
  directory: string;
  manifest_path: string;
  manifest_rel_path: string;
  license: string;
  assets: GeneratedBuiltinAssetResult[];
  created_count: number;
  unchanged_count: number;
  preserved_count: number;
  overwritten_count: number;
}

interface BuiltinPayload {
  id: string;
  fileName: string;
  kind: BuiltinAssetKind;
  format: 'svg' | 'wav';
  description: string;
  buffer: Buffer;
  sha256: string;
  width?: number;
  height?: number;
  audio?: SfxAudioMetrics;
}

const sha256Hex = (buf: Uint8Array): string => crypto.createHash('sha256').update(buf).digest('hex');

let cachedPayloads: readonly BuiltinPayload[] | null = null;

/** 按需生成并缓存全部确定性内置素材缓冲，避免在项目初始化等高频场景重复合成 WAV。 */
function builtinPayloads(): readonly BuiltinPayload[] {
  if (cachedPayloads) return cachedPayloads;
  const list: BuiltinPayload[] = [];
  for (const spec of BuiltinTextureSpecs) {
    const buffer = Buffer.from(spec.generate(), 'utf8');
    list.push({
      id: spec.id,
      fileName: spec.fileName,
      kind: 'texture',
      format: 'svg',
      description: spec.description,
      buffer,
      sha256: sha256Hex(buffer),
      width: spec.width,
      height: spec.height,
    });
  }
  for (const spec of BuiltinSfxSpecs) {
    const buffer = spec.generate();
    const audio = measurePcm16Metrics(buffer);
    list.push({
      id: spec.id,
      fileName: spec.fileName,
      kind: 'sfx',
      format: 'wav',
      description: spec.description,
      buffer,
      sha256: sha256Hex(buffer),
      audio,
    });
  }
  list.sort((a, b) => compareBytes(a.id, b.id));
  cachedPayloads = list;
  return cachedPayloads;
}

/** 所有可用的内置零版权基础素材 ID 列表。 */
export function builtinAssetIds(): string[] {
  return builtinPayloads().map((item) => item.id);
}

/**
 * 将程序化零版权（MIT）基础质感与转场音效落盘到 <projectDir>/assets/builtin/，
 * 并写出确定性的 manifest.json（含 MIT 许可、SHA-256 与时长/峰值元数据）。
 *
 * 默认不覆盖用户已手动修改的文件（标记为 preserved / user_modified: true）。
 */
export function generateBaseAssets(projectDir: string, opts: GenerateBaseAssetsOptions = {}): GenerateBaseAssetsResult {
  const root = path.resolve(projectDir);
  const outDir = path.join(root, BuiltinAssetsRelDir);
  const force = Boolean(opts.force);
  const all = builtinPayloads();

  let selected = all;
  if (opts.only && opts.only.length > 0) {
    const validIds = new Set(all.map((item) => item.id));
    const wanted = new Set<string>();
    for (const raw of opts.only) {
      const id = raw.trim().toLowerCase();
      if (!id) continue;
      if (!validIds.has(id)) {
        throw new Error(`未知的基础素材 ID：${raw}（可选：${all.map((item) => item.id).join('、')}）`);
      }
      wanted.add(id);
    }
    if (wanted.size > 0) selected = all.filter((item) => wanted.has(item.id));
  }

  fs.mkdirSync(outDir, { recursive: true });

  const results: GeneratedBuiltinAssetResult[] = [];
  let createdCount = 0;
  let unchangedCount = 0;
  let preservedCount = 0;
  let overwrittenCount = 0;

  for (const item of selected) {
    const absFile = path.join(outDir, item.fileName);
    const relFile = `${BuiltinAssetsRelDir}/${item.fileName}`;
    let status: BuiltinAssetStatus;
    let finalBytes = item.buffer.length;
    let finalSha = item.sha256;
    let userModified = false;
    let audioMetrics = item.audio;

    if (fs.existsSync(absFile)) {
      const existing = fs.readFileSync(absFile);
      const existingSha = sha256Hex(existing);
      if (existingSha === item.sha256) {
        status = 'unchanged';
        unchangedCount++;
      } else if (force) {
        atomicWrite(absFile, item.buffer, 0o644);
        status = 'overwritten';
        overwrittenCount++;
      } else {
        status = 'preserved';
        userModified = true;
        finalBytes = existing.length;
        finalSha = existingSha;
        preservedCount++;
        if (item.format === 'wav') {
          try {
            audioMetrics = measurePcm16Metrics(existing);
          } catch {
            audioMetrics = undefined;
          }
        }
      }
    } else {
      atomicWrite(absFile, item.buffer, 0o644);
      status = 'created';
      createdCount++;
    }

    results.push({
      id: item.id,
      file: relFile,
      kind: item.kind,
      format: item.format,
      license: BuiltinLicense,
      description: item.description,
      bytes: finalBytes,
      sha256: finalSha,
      user_modified: userModified,
      width: item.width,
      height: item.height,
      duration_seconds: audioMetrics?.duration_seconds,
      sample_rate: audioMetrics?.sample_rate,
      channels: audioMetrics?.channels,
      bit_depth: audioMetrics?.bit_depth,
      rms_db: audioMetrics?.rms_db,
      sample_peak_db: audioMetrics?.sample_peak_db,
      true_peak_dbtp: audioMetrics?.true_peak_dbtp,
      status,
    });
  }

  // 构建清单：若本次仅生成子集，保留目录里已存在的其他内置素材条目。
  const manifestAbs = path.join(outDir, BuiltinManifestFile);
  const manifestRel = `${BuiltinAssetsRelDir}/${BuiltinManifestFile}`;
  const merged = new Map<string, BuiltinAssetEntry>();
  if (selected.length < all.length && fs.existsSync(manifestAbs)) {
    try {
      const prev = JSON.parse(fs.readFileSync(manifestAbs, 'utf8')) as Partial<BuiltinAssetsManifest>;
      for (const entry of prev.assets ?? []) {
        if (entry && typeof entry.id === 'string') merged.set(entry.id, entry);
      }
    } catch {
      // 清单损坏时按本次选中项重建。
    }
  }
  for (const res of results) {
    const { status: _status, ...entry } = res;
    merged.set(entry.id, entry);
  }
  const manifest: BuiltinAssetsManifest = {
    version: 1,
    license: BuiltinLicense,
    license_notice: BuiltinLicenseNotice,
    assets: [...merged.values()].sort((a, b) => compareBytes(a.id, b.id)),
  };
  atomicWrite(manifestAbs, `${marshalIndent(manifest, '  ', false)}\n`, 0o644);

  return {
    directory: outDir,
    manifest_path: manifestAbs,
    manifest_rel_path: manifestRel,
    license: BuiltinLicense,
    assets: results,
    created_count: createdCount,
    unchanged_count: unchangedCount,
    preserved_count: preservedCount,
    overwritten_count: overwrittenCount,
  };
}
