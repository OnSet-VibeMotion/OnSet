import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { test, expect, openProject, openPage } from './fixtures.mjs';

test('shows all six auditions together without nested borders, synchronizes playback and expands the view', async ({ page, project }) => {
  const id = 'audition-20261117-120000';
  const root = path.join(project.path, 'production/studio/auditions', id);
  fs.mkdirSync(root, { recursive: true });
  const sample = path.join(root, 'sample.mp4');
  execFileSync('ffmpeg', ['-v', 'error', '-f', 'lavfi', '-i', 'testsrc2=s=640x360:r=30:d=8', '-pix_fmt', 'yuv420p', sample]);
  const contestants = [...'ABCDEF'].map(slot => {
    const dir = path.join(root, slot);
    fs.mkdirSync(dir);
    fs.copyFileSync(sample, path.join(dir, 'out.mp4'));
    return { slot, renderer: 'claude', model: 'secret-model', workdir: path.relative(project.path, dir), status: 'done', outcome: 'succeeded', output: path.relative(project.path, path.join(dir, 'out.mp4')), error: '' };
  });
  fs.writeFileSync(path.join(root, 'audition.json'), JSON.stringify({ id, scene_id: 'scene-001', scene_dir: 'scenes/scene-001', created_at: new Date().toISOString(), contestants, verdict: null }));
  await openProject(page, project);
  await openPage(page, 'audition');
  const compare = page.locator('.audition-compare');
  const videos = compare.locator('video');
  await expect(videos).toHaveCount(6);
  await expect(compare.getByRole('button', { name: '一起播放', exact: true })).toBeEnabled();
  const panes = await compare.locator('.audition-screen-media').evaluateAll(elements => elements.map(e => {
    const r = e.getBoundingClientRect(); return { x: r.x, y: r.y, width: r.width, height: r.height };
  }));
  expect(Math.abs(panes[0].y - panes[1].y)).toBeLessThan(1);
  expect(Math.abs(panes[0].width - panes[1].width)).toBeLessThan(1);
  expect(panes[0].width).toBeGreaterThan(180);
  expect(Math.abs(panes[0].y - panes[2].y)).toBeLessThan(1);
  expect(panes[3].y).toBeGreaterThan(panes[0].y);
  expect(panes[5].y).toBe(panes[3].y);
  expect(await compare.evaluate(e => getComputedStyle(e).borderTopWidth)).toBe('0px');
  expect(await compare.locator('.audition-screen-media').first().evaluate(e => getComputedStyle(e).borderTopWidth)).toBe('0px');
  await compare.getByRole('button', { name: '一起播放', exact: true }).click();
  await expect.poll(() => videos.evaluateAll(vs => vs.every(v => !v.paused && v.currentTime > 0.2))).toBe(true);
  await compare.getByRole('button', { name: '暂停', exact: true }).click();
  await expect.poll(() => videos.evaluateAll(vs => vs.every(v => v.paused))).toBe(true);
  await compare.getByLabel('对比播放位置').fill('3.5');
  await expect.poll(() => videos.evaluateAll(vs => vs.every(v => Math.abs(v.currentTime - 3.5) < 0.05))).toBe(true);
  await expect(page.locator('.audition')).not.toContainText('secret-model');
  await compare.scrollIntoViewIfNeeded();
  await page.screenshot({ path: test.info().outputPath('audition-compare.png'), animations: 'disabled' });
  await compare.getByRole('button', { name: '放大 F', exact: true }).click();
  await expect(compare.locator('.audition-screen:visible')).toHaveCount(1);
  await compare.getByRole('button', { name: '返回全部画面' }).click();
  await expect(compare.locator('.audition-screen:visible')).toHaveCount(6);
  await compare.getByRole('button', { name: '铺满窗口', exact: true }).click();
  await expect(compare).toHaveAttribute('role', 'dialog');
  // 展开后覆盖了 Electron 标题栏：必须显式退出原生拖动区域，否则鼠标点击会被窗口拖动吞掉。
  expect(await compare.evaluate(e => getComputedStyle(e).getPropertyValue('-webkit-app-region'))).toBe('no-drag');
  const bounds = await compare.boundingBox();
  expect(bounds.x).toBe(0);
  expect(bounds.y).toBe(0);
  await expect(compare.locator('.audition-screen:visible')).toHaveCount(6);
  await page.screenshot({ path: test.info().outputPath('audition-compare-expanded.png'), animations: 'disabled' });
  await compare.getByRole('button', { name: '收起对比', exact: true }).click();
  await expect(compare).toHaveAttribute('role', 'region');
  await expect.poll(() => videos.evaluateAll(vs => vs.every(v => Math.abs(v.currentTime - 3.5) < 0.05))).toBe(true);
  await compare.getByRole('button', { name: '铺满窗口', exact: true }).click();
  await page.keyboard.press('Escape');
  await expect(compare).toHaveAttribute('role', 'region');
  await page.setViewportSize({ width: 900, height: 800 });
  await compare.scrollIntoViewIfNeeded();
  expect(await compare.evaluate(e => e.scrollWidth <= e.clientWidth)).toBe(true);
  await expect(compare.locator('.audition-screen:visible')).toHaveCount(6);
  await page.screenshot({ path: test.info().outputPath('audition-compare-narrow.png'), animations: 'disabled' });
});
